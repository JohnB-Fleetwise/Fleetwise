function randomNear(base: GeoPoint, spreadKm: number): GeoPoint {
  // ~0.009 degrees ≈ 1 km
  const degPerKm = 0.009;
  return {
    latitude: base.latitude + (Math.random() - 0.5) * spreadKm * degPerKm * 2,
    longitude: base.longitude + (Math.random() - 0.5) * spreadKm * degPerKm * 2,
  };
}

