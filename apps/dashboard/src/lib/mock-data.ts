export function getDriverDisplay(driver: Driver): DriverDisplay {
  if (driver.name && driver.email) {
    return { ...driver, name: driver.name, email: driver.email };
  }
  const info = DRIVER_NAMES[driver.id] ?? { name: "Unknown", email: "unknown@fleetwise.com" };
  return { ...driver, ...info };
}

export function getDriverDisplayById(id: string): DriverDisplay | undefined {
  const d = MOCK_DRIVERS.find((dr) => dr.id === id);
  if (!d) return undefined;
  return getDriverDisplay(d);
}

export function getVehicleDriverName(vehicle: Vehicle): string {
  if (!vehicle.assignedDriverId) return "—";
  return DRIVER_NAMES[vehicle.assignedDriverId]?.name ?? "Unknown";
}
